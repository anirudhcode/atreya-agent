RequiredBy=wg-quick@wg0.service
ConditionPathExists=/data/hermes/wireguard.conf

[Service]
Type=oneshot
ExecStart=/usr/local/bin/hermes-wireguard-restore
RemainAfterExit=yes

[Install]
WantedBy=multi-user.target
UNIT

