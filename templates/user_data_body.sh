ATTACHED_TO=$(aws ec2 describe-volumes --volume-ids "$VOL_ID" \
  --query 'Volumes[0].Attachments[0].InstanceId' --output text)
if [ "$ATTACHED_TO" != "$INSTANCE_ID" ]; then
  # Old instance may still be releasing the volume after a spot kill: retry.
  for _ in $(seq 1 30); do
    STATE=$(aws ec2 describe-volumes --volume-ids "$VOL_ID" \
      --query 'Volumes[0].State' --output text)
    if [ "$STATE" = "available" ]; then
      aws ec2 attach-volume --volume-id "$VOL_ID" \
        --instance-id "$INSTANCE_ID" --device /dev/sdf && break
    fi
    sleep 10
  done
