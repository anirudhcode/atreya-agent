[Unit]
RequiresMountsFor=/data

[Service]
StateDirectory=
ExecStart=
ExecStart=/usr/sbin/tailscaled --statedir=/data/tailscale --socket=/run/tailscale/tailscaled.sock --port=${PORT}
UNIT

