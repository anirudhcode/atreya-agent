# ---- Tailscale: reliable private access (rejoins the tailnet every boot) ----
# Outbound-only: no inbound port or security-group change needed (NAT
# traversal + DERP relay). Node identity lives on /data so the same node — and
# its MagicDNS name — survives spot replacement. The auth key is a reusable,
# non-expiring key stored in SSM (same pattern as the other secrets).
