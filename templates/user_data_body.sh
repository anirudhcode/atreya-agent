Wants=network-online.target

[Service]
Type=simple
User=ubuntu
Environment=HERMES_HOME=/data/hermes/hermes-home
Environment=HOME=/home/ubuntu
Environment=PATH=/home/ubuntu/.local/bin:/usr/local/bin:/usr/bin:/bin
ExecStart=/usr/local/bin/hermes gateway
Restart=on-failure
RestartSec=10

[Install]
WantedBy=multi-user.target
UNIT

systemctl daemon-reload
systemctl enable hermes-gateway
systemctl start hermes-gateway 2>/dev/null || true

# ---- update graceful shutdown ----
cat > /usr/local/bin/hermes-shutdown <<'SCRIPT'
#!/bin/bash
set -euo pipefail
systemctl stop hermes-gateway 2>/dev/null || true
systemctl stop hermes-dashboard 2>/dev/null || true
SCRIPT
chmod 755 /usr/local/bin/hermes-shutdown

echo "hermes phase-3 bootstrap complete"



# ===========================================================================
# Phase 3b: AWS Profile setup
# ===========================================================================

# --- Session Manager plugin ---
SMP_BASE=https://s3.amazonaws.com/session-manager-downloads/plugin/latest
case "$(uname -m)" in
  x86_64)  RPM_DIR=linux_64bit;  DEB_DIR=ubuntu_64bit ;;
  aarch64) RPM_DIR=linux_arm64;  DEB_DIR=ubuntu_arm64 ;;
  *) echo "unsupported arch $(uname -m)"; exit 1 ;;
esac
if command -v dpkg >/dev/null 2>&1; then
  curl -fsSLo /tmp/session-manager-plugin.deb "$SMP_BASE/$DEB_DIR/session-manager-plugin.deb"
  dpkg -i /tmp/session-manager-plugin.deb
else
  curl -fsSLo /tmp/session-manager-plugin.rpm "$SMP_BASE/$RPM_DIR/session-manager-plugin.rpm"
  (command -v dnf >/dev/null && dnf install -y /tmp/session-manager-plugin.rpm) || yum install -y /tmp/session-manager-plugin.rpm
fi
session-manager-plugin --version
# --- end Session Manager plugin ---


# --- AtreyaAccessRole cross-account profile ---
cat > /usr/local/bin/atreya-dev-creds <<'EOF'
#!/bin/sh
# Assume AtreyaAccessRole with the source identity required by its trust policy.
# Uses the instance role; unset AWS_PROFILE to avoid recursing into dev-access.
unset AWS_PROFILE
exec aws sts assume-role \
  --role-arn arn:aws:iam::535586744241:role/AtreyaAccessRole \
  --role-session-name hermes-ssm \
  --source-identity ops-agent \
  --query 'Credentials.{Version:`1`,AccessKeyId:AccessKeyId,SecretAccessKey:SecretAccessKey,SessionToken:SessionToken,Expiration:Expiration}' \
  --output json
EOF
chmod 755 /usr/local/bin/atreya-dev-creds

mkdir -p /etc/aws
cat > /etc/aws/config <<'EOF'
[profile dev-access]
credential_process = /usr/local/bin/atreya-dev-creds
region = ap-south-1
EOF
chmod 644 /etc/aws/config

echo 'AWS_CONFIG_FILE=/etc/aws/config' >> /etc/environment
echo 'export AWS_CONFIG_FILE=/etc/aws/config' > /etc/profile.d/aws-config.sh
# --- end AtreyaAccessRole profile ---


# ===========================================================================
# Phase 4: MCP + Gateway secrets — fetch from SSM, inject into config
# ===========================================================================

HERMES_HOME=/data/hermes/hermes-home

# ---- fetch all Phase 4 secrets from SSM ----
GITHUB_PAT=$(aws ssm get-parameter --name "$GITHUB_PAT_SSM" \
  --with-decryption --query 'Parameter.Value' --output text)
SLACK_BOT_TOKEN=$(aws ssm get-parameter --name "$SLACK_BOT_TOKEN_SSM" \
  --with-decryption --query 'Parameter.Value' --output text)
SLACK_APP_TOKEN=$(aws ssm get-parameter --name "$SLACK_APP_TOKEN_SSM" \
  --with-decryption --query 'Parameter.Value' --output text)
ICLOUD_APP_PASSWORD=$(aws ssm get-parameter --name "$ICLOUD_APP_PASSWORD_SSM" \
  --with-decryption --query 'Parameter.Value' --output text)
POSTMAN_API_KEY=$(aws ssm get-parameter --name "$POSTMAN_API_KEY_SSM" \
  --with-decryption --query 'Parameter.Value' --output text)
PLANE_API_KEY=$(aws ssm get-parameter --name "$PLANE_API_KEY_SSM" \
  --with-decryption --query 'Parameter.Value' --output text)
PLANE_PERSONAL_API_KEY=$(aws ssm get-parameter --name "$PLANE_PERSONAL_API_KEY_SSM" \
  --with-decryption --query 'Parameter.Value' --output text)


# ---- MCP server binaries (hermes-postman-mcp, hermes-plane-mcp) ----
curl -fsSL "https://github.com/anirudhcode/hermes-postman-mcp/releases/latest/download/hermes-postman-mcp-linux-arm64" \
  -o /usr/local/bin/hermes-postman-mcp
chmod 755 /usr/local/bin/hermes-postman-mcp

curl -fsSL "https://github.com/anirudhcode/hermes-plane-mcp/releases/latest/download/hermes-plane-mcp-linux-arm64" \
  -o /usr/local/bin/hermes-plane-mcp
chmod 755 /usr/local/bin/hermes-plane-mcp

# ---- GitHub MCP in config.yaml (idempotent) ----
if ! grep -q 'mcp_servers:' "$HERMES_HOME/config.yaml"; then
  cat >> "$HERMES_HOME/config.yaml" <<MCPEOF

mcp_servers:
  github:
    url: https://api.githubcopilot.com/mcp
    headers:
      Authorization: "Bearer $GITHUB_PAT"
    tools:
      include:
        - list_issues
        - get_issue
        - create_issue
        - update_issue
        - list_pull_requests
        - get_pull_request
        - search_code
        - search_issues
        - list_commits
        - get_workflow_runs
    prompts: false
    resources: false
MCPEOF
else
  # Refresh GitHub PAT on subsequent boots
  sed -i "s|Authorization: \"Bearer ghp_[^\"]*\"|Authorization: \"Bearer $GITHUB_PAT\"|" "$HERMES_HOME/config.yaml"
  sed -i "s|Authorization: Bearer ghp_[^[:space:]]*|Authorization: Bearer $GITHUB_PAT|" "$HERMES_HOME/config.yaml"
fi

# ---- Slack MCP in config.yaml (idempotent) ----
if ! grep -q "'@modelcontextprotocol/server-slack'" "$HERMES_HOME/config.yaml"; then
  cat >> "$HERMES_HOME/config.yaml" <<SLACKMCP
  slack:
    command: npx
    args:
      - "-y"
      - "@modelcontextprotocol/server-slack"
    env:
      SLACK_BOT_TOKEN: "$SLACK_BOT_TOKEN"
      SLACK_TEAM_ID: "T08G5VDS9S8"
    tools:
      include:
        - slack_list_channels
        - slack_post_message
        - slack_reply_to_thread
        - slack_get_channel_history
        - slack_get_thread_replies
        - slack_get_users
        - slack_get_user_profile
        - slack_add_reaction
    prompts: false
    resources: false
SLACKMCP
else
  # Refresh Slack bot token in MCP config on subsequent boots
  sed -i "/SLACK_BOT_TOKEN:/s|:.*|: \"$SLACK_BOT_TOKEN\"|" "$HERMES_HOME/config.yaml"
fi

# ---- Postman MCP in config.yaml (idempotent) ----
if ! grep -q 'command: /usr/local/bin/hermes-postman-mcp' "$HERMES_HOME/config.yaml" 2>/dev/null; then
  cat >> "$HERMES_HOME/config.yaml" <<POSTMANMCP
  postman:
    command: /usr/local/bin/hermes-postman-mcp
    args: []
    env:
      POSTMAN_API_KEY: "$POSTMAN_API_KEY"
    prompts: false
    resources: false
POSTMANMCP
else
  sed -i "/POSTMAN_API_KEY:/s|:.*|: \"$POSTMAN_API_KEY\"|" "$HERMES_HOME/config.yaml"
fi


# ---- Plane MCP in config.yaml (idempotent) ----
if ! grep -q 'command: /usr/local/bin/hermes-plane-mcp' "$HERMES_HOME/config.yaml" 2>/dev/null; then
  cat >> "$HERMES_HOME/config.yaml" <<PLANEMCP
  plane-work:
    command: /usr/local/bin/hermes-plane-mcp
    args: []
    env:
      PLANE_API_KEY: "$PLANE_API_KEY"
      PLANE_DEFAULT_WORKSPACE: "appstorys"
    prompts: false
    resources: false
  plane-personal:
    command: /usr/local/bin/hermes-plane-mcp
    args: []
    env:
      PLANE_API_KEY: "$PLANE_PERSONAL_API_KEY"
      PLANE_DEFAULT_WORKSPACE: "atreya"
    prompts: false
    resources: false
PLANEMCP
else
  sed -i "/^  plane-work:/,/^  [a-z]\|^[a-z]/{s|PLANE_API_KEY:.*|PLANE_API_KEY: \"$PLANE_API_KEY\"|}" \
    "$HERMES_HOME/config.yaml"
  sed -i "/^  plane-personal:/,/^  [a-z]\|^[a-z]/{s|PLANE_API_KEY:.*|PLANE_API_KEY: \"$PLANE_PERSONAL_API_KEY\"|}" \
    "$HERMES_HOME/config.yaml"
fi

# ---- Platform config in config.yaml (idempotent) ----
if ! grep -q 'email:' "$HERMES_HOME/config.yaml" 2>/dev/null; then
  # Add email platform if not present
  sed -i '/^platforms:/,/^[^ ]/{/enabled: true/!b; /slack/{a\  email:\n    enabled: true
}}' "$HERMES_HOME/config.yaml"
fi

# ---- Slack require_mention (idempotent) ----
if ! grep -q '^slack:' "$HERMES_HOME/config.yaml" 2>/dev/null; then
  cat >> "$HERMES_HOME/config.yaml" <<'SLACKCONF'

slack:
  require_mention: true
SLACKCONF
fi

if [ ! -f "$HERMES_HOME/.env" ]; then
  install -m 600 -o ubuntu -g ubuntu /dev/null "$HERMES_HOME/.env"
fi
chown ubuntu:ubuntu "$HERMES_HOME/.env"
chmod 600 "$HERMES_HOME/.env"

# ---- .env: Slack gateway secrets (refresh every boot) ----
# Add or update Slack env vars
for VAR_LINE in \
  "SLACK_BOT_TOKEN=$SLACK_BOT_TOKEN" \
  "SLACK_APP_TOKEN=$SLACK_APP_TOKEN" \
  "SLACK_ALLOWED_USERS=U0915EHM5PU,U08G5VDT1FE,U0CC6BAPRB4,U0AFAH5T89J,U0CBRNRR72B,U0CBREP9H9D,U0CBRNN12LF,U0CC1R9AJ05,U0CCAQW93MJ,U0CD1FF0UD6" \
  "SLACK_HOME_CHANNEL=D0BGSV3JSUU" \
  "SLACK_ENABLED=true"; do
  VAR_NAME="${VAR_LINE%%=*}"
  if grep -q "^${VAR_NAME}=" "$HERMES_HOME/.env"; then
    sed -i "s|^${VAR_NAME}=.*|${VAR_LINE}|" "$HERMES_HOME/.env"
  else
    echo "$VAR_LINE" >> "$HERMES_HOME/.env"
  fi
done

# ---- .env: Email gateway secrets (refresh every boot) ----
for VAR_LINE in \
  "EMAIL_ADDRESS=anirudhcode@icloud.com" \
  "EMAIL_PASSWORD=$ICLOUD_APP_PASSWORD" \
  "EMAIL_IMAP_HOST=imap.mail.me.com" \
  "EMAIL_SMTP_HOST=smtp.mail.me.com" \
  "EMAIL_IMAP_PORT=993" \
  "EMAIL_SMTP_PORT=587" \
  "EMAIL_POLL_INTERVAL=60" \
  "EMAIL_ALLOWED_USERS=" \
  "EMAIL_HOME_ADDRESS=anirudh@anirudhcode.dev"; do
  VAR_NAME="${VAR_LINE%%=*}"
  if grep -q "^${VAR_NAME}=" "$HERMES_HOME/.env"; then
    sed -i "s|^${VAR_NAME}=.*|${VAR_LINE}|" "$HERMES_HOME/.env"
  else
    echo "$VAR_LINE" >> "$HERMES_HOME/.env"
  fi
done

# ---- clear secrets from memory ----
unset GITHUB_PAT SLACK_BOT_TOKEN SLACK_APP_TOKEN ICLOUD_APP_PASSWORD POSTMAN_API_KEY PLANE_API_KEY PLANE_PERSONAL_API_KEY

systemctl restart hermes-gateway 2>/dev/null || true

echo "hermes phase-4 bootstrap complete"